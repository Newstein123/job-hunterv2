<?php

namespace App\Services\AiService;

use App\Enums\ApplicationStatus;
use App\Models\Application;
use App\Models\Resume;
use Illuminate\Support\Facades\DB;

/**
 * Runs the AI pipeline for an application and persists its structured outputs.
 */
class ApplicationGenerator
{
    public function __construct(
        private readonly AiServiceClient $client,
        private readonly AnalysisRecorder $recorder,
        private readonly UsageRecorder $usage,
    ) {}

    public function generate(Application $application): void
    {
        $application->loadMissing(['job', 'user.careerProfile', 'user.applicationRule']);
        $user = $application->user;
        $resumes = $user->resumes()->where('is_active', true)->get();
        // The user chose which resume to send (speculative applications); otherwise the best fit is picked.
        $chosen = $resumes->where('id', $application->job->preferred_resume_id);
        if ($application->job->preferred_resume_id && $chosen->isNotEmpty()) {
            $resumes = $chosen->values();
        }

        if (! $user->careerProfile) {
            throw new AiServiceException('Add your career profile before generating an application', 422);
        }
        if ($resumes->isEmpty()) {
            throw new AiServiceException('Upload at least one active resume before generating an application', 422);
        }

        $result = $this->client->generateApplication(
            PipelinePayload::forApplication($user, $application->job, $resumes)
        );

        $this->store($application, $result, $resumes->map(fn (Resume $r) => $r->id)->values()->all());
    }

    /**
     * @param  array<string, mixed>  $result  PipelineResult JSON
     * @param  array<int, int>  $resumeIds
     */
    public function store(Application $application, array $result, array $resumeIds): void
    {
        $recommended = (int) ($result['resume_selection']['recommended_resume_id'] ?? 0);
        if (! in_array($recommended, $resumeIds, true)) {
            throw new AiServiceException('The AI service recommended an unknown resume', 422);
        }

        DB::transaction(function () use ($application, $result, $recommended, $resumeIds) {
            $this->recorder->record($application->job, $result, $resumeIds, $application->user->profileVersion());
            $this->usage->record($result['meta']['usage'] ?? null, $application->user_id, $application->job_id, $application->id);

            $application->strategies()->create([
                'match' => $result['match'],
                'resume_selection' => $result['resume_selection'],
                'skill_strategy' => $result['skill_strategy'],
                'application_strategy' => $result['application_strategy'],
                'meta' => $result['meta'],
            ]);

            $email = $result['email'];
            $application->transitionTo(ApplicationStatus::Generated, note: 'Generated by AI pipeline', attributes: [
                'resume_id' => $recommended,
                'generation_state' => Application::GENERATION_DONE,
                'generation_error' => null,
                'subject' => $email['subject'],
                'body' => $email['body'],
                'cover_letter' => $email['cover_letter'],
                'validation' => $email['validation'],
                'edited_at' => null,
            ]);
        });
    }
}
